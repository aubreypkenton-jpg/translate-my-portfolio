"""
Two small, related outputs for someone who wants to take this analysis with
them: a one-line plain-text summary (for pasting/sharing), and a structured
JSON export of the full analysis (for keeping or feeding into something
else). Both are built from the same result dict everything else uses --
nothing new is computed here.
"""
from datetime import datetime, timezone


def build_summary_text(result: dict) -> str:
    """One shareable sentence summarizing the headline numbers."""
    parts = [f"My portfolio: ${result['total_value']:,.0f}"]

    if result.get("risk_score") is not None:
        parts.append(f"{result['risk_score']:.0f}/100 risk ({result['risk_label']})")

    c = result["concentration"]
    if c["top_ticker"]:
        parts.append(f"largest position {c['top_ticker']} at {c['top_pct']:.0f}%")

    worst_dd = None
    for name, dd in result["drawdown_scenarios"].items():
        v = dd["estimated_portfolio_change_pct"]
        if worst_dd is None or v < worst_dd[1]:
            worst_dd = (name, v)
    if worst_dd:
        parts.append(f"would have fallen ~{abs(worst_dd[1]):.0f}% in the {worst_dd[0]}")

    return " -- ".join(parts) + ". (via Translate My Portfolio)"


def build_export_json(result: dict, checklist: list) -> dict:
    """Structured, JSON-safe export of the analysis (no pandas objects)."""
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "total_value": round(result["total_value"], 2),
        "holdings": [
            {
                "ticker": r["ticker"],
                "sector": r["sector"],
                "value": round(r["value"], 2),
                "weight_pct": round(r["weight_pct"], 2),
                "gain_loss_pct": round(r["gain_loss_pct"], 2) if r["gain_loss_pct"] is not None else None,
                "max_drawdown_pct": round(r["max_drawdown_pct"], 2) if r["max_drawdown_pct"] is not None else None,
            }
            for r in result["rows"]
        ],
        "effective_holdings": result.get("effective_holdings"),
        "risk_score": result.get("risk_score"),
        "risk_label": result.get("risk_label"),
        "portfolio_volatility_pct": result.get("portfolio_vol"),
        "portfolio_cagr_pct": result.get("portfolio_cagr"),
        "portfolio_max_drawdown_pct": result.get("portfolio_max_drawdown"),
        "sharpe_ratio": result.get("sharpe_ratio"),
        "sortino_ratio": result.get("sortino_ratio"),
        "beta_vs_sp500": result.get("beta"),
        "risk_free_rate_pct": result.get("risk_free_rate_pct"),
        "analysis_window": result.get("analysis_window"),
        "hhi": result.get("hhi"),
        "asset_class_pct": result.get("asset_class_pct"),
        "fund_flags": result.get("fund_flags"),
        "weighted_expense_ratio_pct": result.get("weighted_expense_ratio_pct"),
        "tax_summary": result.get("tax_summary"),
        "flagged_sectors": result.get("flagged_sectors"),
        "high_correlation_pairs": [
            {"a": a, "b": b, "correlation": round(v, 3)} for a, b, v in result.get("high_corr_pairs", [])
        ],
        "drawdown_scenarios": result.get("drawdown_scenarios"),
        "behavioral_flags": result.get("behavioral_flags"),
        "tax_flags": result.get("tax_flags"),
        "benchmark": result.get("benchmark"),
        "checklist": checklist,
        "disclaimer": ("Educational only; not investment, tax, or legal advice. "
                       "Generated by Translate My Portfolio from Yahoo Finance data."),
    }
